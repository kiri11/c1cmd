import C1Kit
import Foundation

/// Files generated from the sources: `scripts/v2-generate.sh` writes them, and every test run checks them.
enum Generated {
    static let sdef = "sdef/16.8.5.30.sdef"

    static func files() throws -> [(path: String, content: String)] {
        [("Sources/C1Kit/Generated/Embedded.swift", try embedded())]
    }

    static func embedded() throws -> String {
        func text(_ path: String) throws -> String {
            try String(contentsOfFile: path, encoding: .utf8).trimmingCharacters(in: .newlines)
        }
        let terms = try Terminology(sdef: Data(contentsOf: URL(fileURLWithPath: sdef))).used().encoded()
        func literal(_ name: String, _ value: String) -> String {
            "    static let \(name) = #\"\"\"\n\(value)\n\"\"\"#\n"
        }
        return "// Generated by scripts/v2-generate.sh from Sources/C1Kit/Resources and \(sdef); do not edit.\n"
            + "enum Embedded {\n"
            + literal("defaults", try text("Sources/C1Kit/Resources/Defaults.json"))
            + literal("bounds", try text("Sources/C1Kit/Resources/Bounds.json"))
            + literal("terms", terms)
            + "}\n"
    }

    /// Writes every file, or with `write` false checks that each is current.
    static func run(write: Bool) {
        let files: [(path: String, content: String)]
        do { files = try self.files() } catch { return check(false, "cannot generate: \(error)") }
        for file in files {
            let current = try? String(contentsOfFile: file.path, encoding: .utf8)
            if write {
                if current != file.content { try! file.content.write(toFile: file.path, atomically: true, encoding: .utf8); print("wrote \(file.path)") }
            } else {
                check(current == file.content, "\(file.path) is stale; run scripts/v2-generate.sh")
            }
        }
    }
}
